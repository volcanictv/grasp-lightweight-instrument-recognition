"""Milestone 0: dataset inspection.

Parses the official GraSP short-term annotation files, computes counts,
class/co-occurrence/resolution statistics, checks frame and mask files on
disk for missing or corrupt entries, dumps sample frame/mask overlays, and
writes docs/dataset_report.md.

Usage:
    python scripts/inspect_dataset.py [--data-root PATH] [--out-dir PATH]

Data root defaults to the GRASP_DATA_ROOT env var, then ./GraSp. Path is
never hardcoded past this fallback, per CLAUDE.md.
"""

from __future__ import annotations

import argparse
import os
import random
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from surgical_ai.data import splits, statistics  # noqa: E402
from surgical_ai.utils import visualization as viz  # noqa: E402


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--data-root",
        type=Path,
        default=Path(os.environ.get("GRASP_DATA_ROOT", REPO_ROOT / "GraSp")),
        help="Root of the GraSP dataset (contains annotations/ and frames-001/).",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=REPO_ROOT / "docs",
        help="Where to write dataset_report.md and figures/samples subdirs.",
    )
    parser.add_argument(
        "--num-samples",
        type=int,
        default=8,
        help="Number of sample frame/mask overlays to dump.",
    )
    parser.add_argument(
        "--skip-integrity",
        action="store_true",
        help="Skip the on-disk missing/corrupt file check (slow: opens every "
        "annotated frame and mask).",
    )
    parser.add_argument("--seed", type=int, default=42)
    return parser.parse_args()


def fmt_histogram(hist: dict, names: dict[int, str]) -> dict[str, int]:
    return {names[k]: v for k, v in sorted(hist.items())}


def main() -> None:
    args = parse_args()
    random.seed(args.seed)

    data_root = args.data_root
    frames_root = data_root / "frames-001" / "frames"
    seg_root = data_root / "annotations" / "segmentations"

    figures_dir = args.out_dir / "figures"
    samples_dir = args.out_dir / "samples"
    figures_dir.mkdir(parents=True, exist_ok=True)
    samples_dir.mkdir(parents=True, exist_ok=True)

    docs = {name: splits.load_short_term(data_root, name) for name in splits.SHORT_TERM_SPLITS}
    names = statistics.category_names(docs["train"])

    report_lines: list[str] = []
    report_lines.append("# GraSP dataset report")
    report_lines.append("")
    report_lines.append(
        "Generated by `scripts/inspect_dataset.py` (Milestone 0). "
        f"Data root: `{data_root}`."
    )
    report_lines.append("")

    # --- category sanity check against CLAUDE.md ---
    claude_md_names = {
        1: "Bipolar Forceps",
        2: "Prograsp Forceps",
        3: "Large Needle Driver",
        4: "Monopolar Curved Scissors",
        5: "Suction Instrument",
        6: "Clip Applier",
        7: "Laparoscopic Grasper",
    }
    mismatches = [
        (cid, claude_md_names[cid], names[cid])
        for cid in sorted(names)
        if claude_md_names.get(cid) != names[cid]
    ]
    if mismatches:
        report_lines.append("## Discrepancy vs CLAUDE.md")
        report_lines.append("")
        report_lines.append(
            "CLAUDE.md lists 7 instrument class names. The annotation JSON's "
            "`categories` field disagrees on the following id(s):"
        )
        report_lines.append("")
        for cid, doc_name, json_name in mismatches:
            report_lines.append(f"- id {cid}: CLAUDE.md says `{doc_name}`, JSON says `{json_name}`")
        report_lines.append("")
        report_lines.append(
            "Code and configs use the JSON category names (source of truth for "
            "training). CLAUDE.md should be corrected to match; flagged in "
            "docs/DECISIONS.md rather than silently overridden."
        )
        report_lines.append("")

    # --- per-split basic counts ---
    report_lines.append("## Split summary")
    report_lines.append("")
    report_lines.append("| split | cases | keyframes | annotated keyframes | instances |")
    report_lines.append("|---|---|---|---|---|")
    for split_name, doc in docs.items():
        counts = statistics.basic_counts(doc)
        cases = splits.case_list(doc)
        report_lines.append(
            f"| {split_name} | {counts['num_cases']} ({', '.join(cases)}) "
            f"| {counts['num_keyframes']} | {counts['num_annotated_keyframes']} "
            f"| {counts['num_instances']} |"
        )
    report_lines.append("")
    report_lines.append(
        "fold1 + fold2 partition the train split exactly (same case set, "
        "disjoint cases, keyframe counts sum to train's). Verified below."
    )
    report_lines.append("")
    train_cases = set(splits.case_list(docs["train"]))
    fold_cases = set(splits.case_list(docs["fold1"])) | set(splits.case_list(docs["fold2"]))
    fold_overlap = set(splits.case_list(docs["fold1"])) & set(splits.case_list(docs["fold2"]))
    fold_keyframe_sum = len(docs["fold1"]["images"]) + len(docs["fold2"]["images"])
    report_lines.append(
        f"- fold1 union fold2 cases == train cases: "
        f"{fold_cases == train_cases}"
    )
    report_lines.append(f"- fold1 / fold2 case overlap: {sorted(fold_overlap) or 'none'}")
    report_lines.append(
        f"- fold1 keyframes ({len(docs['fold1']['images'])}) + fold2 keyframes "
        f"({len(docs['fold2']['images'])}) = {fold_keyframe_sum}, "
        f"train keyframes = {len(docs['train']['images'])}, "
        f"match: {fold_keyframe_sum == len(docs['train']['images'])}"
    )
    report_lines.append("")

    # --- resolution distribution ---
    report_lines.append("## Resolution distribution")
    report_lines.append("")
    for split_name, doc in docs.items():
        res = statistics.resolution_distribution(doc)
        res_str = ", ".join(f"{w}x{h}: {n}" for (w, h), n in res.items())
        report_lines.append(f"- {split_name}: {res_str}")
    report_lines.append("")

    # --- class histograms (train+test combined = whole dataset) ---
    combined_instances = statistics.class_instance_histogram(docs["train"])
    combined_instances.update(statistics.class_instance_histogram(docs["test"]))
    combined_presence = statistics.class_frame_presence_histogram(docs["train"])
    combined_presence.update(statistics.class_frame_presence_histogram(docs["test"]))

    report_lines.append("## Class histogram (train + test combined)")
    report_lines.append("")
    report_lines.append("| class | instances | frames containing class |")
    report_lines.append("|---|---|---|")
    for cid in sorted(names):
        report_lines.append(
            f"| {names[cid]} | {combined_instances.get(cid, 0)} | "
            f"{combined_presence.get(cid, 0)} |"
        )
    report_lines.append("")
    total_annotated_frames = statistics.basic_counts(docs["train"])["num_annotated_keyframes"] + \
        statistics.basic_counts(docs["test"])["num_annotated_keyframes"]
    rarest = min(names, key=lambda c: combined_instances.get(c, 0))
    report_lines.append(
        f"Rarest class by instance count: **{names[rarest]}** "
        f"({combined_instances.get(rarest, 0)} instances, "
        f"{combined_presence.get(rarest, 0)}/{total_annotated_frames} frames)."
    )
    report_lines.append("")

    viz.plot_class_histogram(
        fmt_histogram(combined_instances, names),
        "Instrument instance count (train+test)",
        figures_dir / "class_instance_histogram.png",
    )
    viz.plot_class_histogram(
        fmt_histogram(combined_presence, names),
        "Frames containing each instrument class (train+test)",
        figures_dir / "class_frame_presence_histogram.png",
    )

    # --- per-case histogram (train split, for imbalance-by-case sense) ---
    per_case = statistics.per_case_class_histogram(docs["train"])
    frames_per_case = {img["video_name"]: 0 for img in docs["train"]["images"]}
    for img in docs["train"]["images"]:
        frames_per_case[img["video_name"]] += 1
    viz.plot_frames_per_case(
        dict(sorted(frames_per_case.items())),
        "Annotated keyframes per case (train)",
        figures_dir / "keyframes_per_case_train.png",
    )

    report_lines.append("## Per-case instance histogram (train)")
    report_lines.append("")
    header = "| case | " + " | ".join(names[c] for c in sorted(names)) + " |"
    report_lines.append(header)
    report_lines.append("|" + "---|" * (len(names) + 1))
    for case in sorted(per_case):
        row = [str(per_case[case].get(c, 0)) for c in sorted(names)]
        report_lines.append(f"| {case} | " + " | ".join(row) + " |")
    report_lines.append("")

    # --- multi-instrument-per-frame distribution ---
    inst_per_frame = statistics.instances_per_frame_distribution(docs["train"])
    inst_per_frame.update(statistics.instances_per_frame_distribution(docs["test"]))
    report_lines.append("## Instruments per frame (train + test)")
    report_lines.append("")
    report_lines.append("| instances in frame | number of frames |")
    report_lines.append("|---|---|")
    for k in sorted(inst_per_frame):
        report_lines.append(f"| {k} | {inst_per_frame[k]} |")
    report_lines.append("")
    multi = sum(v for k, v in inst_per_frame.items() if k >= 2)
    report_lines.append(
        f"{multi}/{total_annotated_frames} annotated frames "
        f"({100 * multi / total_annotated_frames:.1f}%) contain 2+ instrument "
        "instances. Confirms the multi-label task framing in CLAUDE.md."
    )
    report_lines.append("")

    # --- co-occurrence matrix (combined) ---
    # cooccurrence_matrix operates on one doc; merge train+test images/annotations.
    # image_id is only unique within a single split file (both start from 1), so
    # naively concatenating would merge unrelated train/test frames that share an
    # id. Offset test ids clear of train's range before merging.
    id_offset = max(img["id"] for img in docs["train"]["images"]) + 1
    test_images = [{**img, "id": img["id"] + id_offset} for img in docs["test"]["images"]]
    test_annotations = [
        {**a, "image_id": a["image_id"] + id_offset} for a in docs["test"]["annotations"]
    ]
    combined_doc = {
        "categories": docs["train"]["categories"],
        "images": docs["train"]["images"] + test_images,
        "annotations": docs["train"]["annotations"] + test_annotations,
    }
    cat_ids, matrix = statistics.cooccurrence_matrix(combined_doc)
    viz.plot_cooccurrence_matrix(
        cat_ids, matrix, names, figures_dir / "cooccurrence_matrix.png"
    )
    report_lines.append("## Co-occurrence matrix")
    report_lines.append("")
    report_lines.append(f"See `figures/cooccurrence_matrix.png`. Diagonal = frames containing that class.")
    report_lines.append("")

    # --- integrity check ---
    if not args.skip_integrity:
        report_lines.append("## Integrity check (missing/corrupt files)")
        report_lines.append("")
        for split_name in ["train", "test"]:
            doc = docs[split_name]
            report = statistics.check_integrity(
                doc, frames_root, seg_root, split=split_name
            )
            report_lines.append(
                f"- {split_name}: checked {report.checked_frames} frames, "
                f"{report.checked_masks} masks. "
                f"Missing frames: {len(report.missing_frames)}. "
                f"Corrupt frames: {len(report.corrupt_frames)}. "
                f"Missing masks: {len(report.missing_masks)}. "
                f"Corrupt masks: {len(report.corrupt_masks)}."
            )
            for label, items in [
                ("missing frames", report.missing_frames),
                ("corrupt frames", report.corrupt_frames),
                ("missing masks", report.missing_masks),
                ("corrupt masks", report.corrupt_masks),
            ]:
                if items:
                    report_lines.append(f"  - {label}: {items[:20]}" + (" ..." if len(items) > 20 else ""))
        report_lines.append("")
    else:
        report_lines.append("## Integrity check")
        report_lines.append("")
        report_lines.append("Skipped (--skip-integrity).")
        report_lines.append("")

    # --- sample frame/mask overlays ---
    report_lines.append("## Sample frame/mask overlays")
    report_lines.append("")
    all_images = [
        (split_name, img)
        for split_name in ["train", "test"]
        for img in docs[split_name]["images"]
    ]
    annotated_ids = {
        split_name: {a["image_id"] for a in docs[split_name]["annotations"]}
        for split_name in ["train", "test"]
    }
    annotated_images = [
        (split_name, img)
        for split_name, img in all_images
        if img["id"] in annotated_ids[split_name]
    ]
    sample = random.sample(annotated_images, min(args.num_samples, len(annotated_images)))
    for split_name, img in sample:
        image_name = img["file_name"]
        frame_path = frames_root / image_name
        mask_file = statistics.mask_path(seg_root, split_name, image_name)
        out_name = image_name.replace("/", "_").replace(".jpg", "_overlay.png")
        out_path = samples_dir / out_name
        if frame_path.exists() and mask_file.exists():
            viz.save_mask_overlay(frame_path, mask_file, out_path)
            report_lines.append(f"- `{image_name}` -> `samples/{out_name}`")
        else:
            report_lines.append(f"- `{image_name}`: skipped, frame or mask missing on disk")
    report_lines.append("")

    report_path = args.out_dir / "dataset_report.md"
    report_path.write_text("\n".join(report_lines), encoding="utf-8")
    print(f"Wrote {report_path}")
    print(f"Figures in {figures_dir}")
    print(f"Sample overlays in {samples_dir}")


if __name__ == "__main__":
    main()
